// Génère docs/guides/*.md (français) et docs/guides/en/*.md (anglais) à partir du contenu STRUCTURÉ de l'application
// (frontend/src/features/guide/structure.js + frontend/src/i18n/guides/*). Une seule source de vérité : ne jamais modifier
// ces fichiers Markdown à la main. Lancer `npm run guides:md` après toute modification d'un guide ; le test
// scripts/__tests__/guides.test.mjs échoue si les fichiers ne correspondent plus.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const RACINE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const front = (chemin) => pathToFileURL(resolve(RACINE, "frontend/src", chemin)).href;

const { GUIDES, NOMS_GUIDES } = await import(front("features/guide/structure.js"));
const { texteBrut } = await import(front("features/guide/guide.js"));
const dictionnaires = { fr: (await import(front("i18n/fr.js"))).default, en: (await import(front("i18n/en.js"))).default };
const textes = {};
for (const guide of NOMS_GUIDES) {
  textes[guide] = {};
  for (const langue of ["fr", "en"]) textes[guide][langue] = (await import(front(`i18n/guides/${guide}.${langue}.js`))).default;
}

const FICHIERS = { pdg: "01-PDG.md", employe: "02-EMPLOYE.md", client: "03-CLIENT.md", superadmin: "04-SUPERADMIN.md" };
const LIBELLES = {
  fr: { toc: "Sommaire", expected: "Résultat attendu", rights: "Droits nécessaires", generated: "Fichier généré par `npm run guides:md` à partir du guide intégré à l'application : ne pas le modifier à la main.", screenshot: "Capture d'écran", other: "Autre langue", readme: "Guides d'utilisation de Tailora", readmeIntro: "Un guide par type d'utilisateur. Chacun est aussi intégré à l'application (menu « Guide d'utilisation ») et s'affiche automatiquement selon le rôle du compte connecté.", employeNote: "Dans l'application, un employé ne voit que les sections et étapes qui correspondent à ses droits ; ce document les présente toutes, avec les droits nécessaires." },
  en: { toc: "Contents", expected: "Expected result", rights: "Required rights", generated: "File generated by `npm run guides:md` from the guide built into the application: do not edit it by hand.", screenshot: "Screenshot", other: "Other language", readme: "Tailora user guides", readmeIntro: "One guide per type of user. Each one is also built into the application (“User guide” menu) and is shown automatically according to the signed-in account's role.", employeNote: "In the application, an employee only sees the sections and steps matching their rights; this document presents them all, with the required rights." },
};

const resoudre = (dico, cle) => cle.split(".").reduce((acc, p) => (acc && typeof acc === "object" ? acc[p] : undefined), dico);
const NOMS_ROLES = { fr: { pdg: "PDG", employe: "Employé", client: "Client(e)", superadmin: "SUPERADMIN" }, en: { pdg: "Owner", employe: "Employee", client: "Client", superadmin: "SUPERADMIN" } };

function guideMarkdown(guide, langue) {
  const L = LIBELLES[langue];
  const dico = dictionnaires[langue];
  const brut = (texte) => texteBrut(texte, (cle) => resoudre(dico, cle));
  const t = textes[guide][langue];
  const prefixeImage = langue === "fr" ? "../../frontend/public/guide/fr" : "../../../frontend/public/guide/en";
  const lignes = [`<!-- ${L.generated} -->`, "", `# ${t.title}`, "", `> ${t.subtitle}`, "", t.intro, ""];
  if (guide === "employe") lignes.push(`> ${L.employeNote}`, "");
  lignes.push(`## ${L.toc}`, "");
  GUIDES[guide].forEach((s, i) => lignes.push(`${i + 1}. [${t.sections[s.id].title}](#${i + 1}-${ancre(t.sections[s.id].title)})`));
  lignes.push("");
  GUIDES[guide].forEach((s, i) => {
    const ts = t.sections[s.id];
    lignes.push(`## ${i + 1}. ${ts.title}`, "");
    if (ts.intro) lignes.push(ts.intro, "");
    if (guide === "employe" && (s.permissions?.length || s.steps.some((e) => e.permissions?.length))) {
      const libelle = (p) => { const [m, a] = p.split("."); return resoudre(dico, `emp.perm.${m}.${a}`) ?? p; };
      const toutes = [...new Set([...(s.permissions ?? []), ...s.steps.flatMap((e) => e.permissions ?? [])])];
      lignes.push(`*${L.rights} :* ${toutes.map(libelle).join(" ; ")}`, "");
    }
    if (s.shot) lignes.push(`![${L.screenshot} : ${ts.title}](${prefixeImage}/${s.shot.id}-desktop.jpg)`, "");
    s.steps.forEach((e, j) => {
      const c = ts.steps[e.id];
      lignes.push(`${j + 1}. ${brut(c.text)}`, `   - **${L.expected} :** ${brut(c.result)}`);
    });
    lignes.push("");
  });
  return lignes.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

// Ancre GitHub d'un titre « N. Titre » : minuscules, sans ponctuation, espaces -> tirets.
function ancre(titre) {
  return titre.toLowerCase().normalize("NFC").replace(/[^\p{L}\p{N}\s-]/gu, "").trim().replace(/\s+/g, "-");
}

function readme(langue) {
  const L = LIBELLES[langue];
  const lignes = [`<!-- ${L.generated} -->`, "", `# ${L.readme}`, "", L.readmeIntro, ""];
  const autre = langue === "fr" ? "[English version](en/README.md)" : "[Version française](../README.md)";
  lignes.push(`${L.other} : ${autre}`, "", "| | |", "|---|---|");
  for (const guide of NOMS_GUIDES) lignes.push(`| ${NOMS_ROLES[langue][guide]} | [${textes[guide][langue].title}](${FICHIERS[guide]}) |`);
  return lignes.join("\n") + "\n";
}

/** Tous les fichiers à produire : { chemin relatif à la racine du dépôt -> contenu }. */
export function fichiersGuides() {
  const sortie = {};
  for (const langue of ["fr", "en"]) {
    const dossier = langue === "fr" ? "docs/guides" : "docs/guides/en";
    sortie[`${dossier}/README.md`] = readme(langue);
    for (const guide of NOMS_GUIDES) sortie[`${dossier}/${FICHIERS[guide]}`] = guideMarkdown(guide, langue);
  }
  return sortie;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [chemin, contenu] of Object.entries(fichiersGuides())) {
    const complet = resolve(RACINE, chemin);
    mkdirSync(dirname(complet), { recursive: true });
    const avant = existsSync(complet) ? readFileSync(complet, "utf8") : null;
    if (avant !== contenu) writeFileSync(complet, contenu);
    console.log(`${avant === contenu ? "inchangé" : "écrit"}  ${chemin}`);
  }
}
